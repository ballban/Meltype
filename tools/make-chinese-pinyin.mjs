// Builds dictionaries/chinese-pinyin.txt from the rime-ice dictionaries (https://github.com/iDvel/rime-ice, GPL-3.0).
// The composition lattice (ReadingLattice.cs) uses it to weigh pinyin spans against Japanese and English.
//   node tools/make-chinese-pinyin.mjs native/rime/bin/data > dictionaries/chinese-pinyin.txt
// The folder needs cn_dicts/8105.dict.yaml and cn_dicts/base.dict.yaml of rime-ice at RimeIceCommit: native/rime/Get-Rime.ps1
// downloads them there ($riceCommit, which must stay the same commit) and checks their SHA-256. A rime-ice checkout also works.
import fs from 'node:fs';
import path from 'node:path';

const RimeIceCommit = '99662ba01e3affa6a0f009174ca530b887bac3b6';
// Syllables by the summed weight of their characters in 8105.dict.yaml. 1M keeps everyday syllables (ni 你 2.1M, men 们 1.5M) common
const CommonSyllableWeight = 1_000_000;
const StandardSyllableWeight = 100_000;
// Words of two or more syllables by their highest weight in base.dict.yaml
const CommonWordWeight = 200_000;
const StandardWordWeight = 50_000;
// Characters that Japanese text cannot contain (not in CP932), weight at least this, mark text as Chinese
const SimplifiedWeight = 10_000;

const root = process.argv[2];
if (!root) {
  console.error('usage: node tools/make-chinese-pinyin.mjs path/to/rime-ice');
  process.exit(1);
}

function* rows(file) {
  let data = false;
  for (const line of fs.readFileSync(path.join(root, 'cn_dicts', file), 'utf8').split('\n')) {
    const trimmed = line.replace(/\r$/, '');
    if (trimmed === '...') { data = true; continue; }
    if (!data || trimmed === '' || trimmed.startsWith('#')) continue;
    const [text, code, weight] = trimmed.split('\t');
    if (code) yield { text, code, weight: Number(weight) || 0 };
  }
}

// Standard pinyin syllables have a vowel (m, n, ng, hm and hng are interjections)
const isSyllable = s => /^[a-z]+$/.test(s) && /[aeiouv]/.test(s);

const syllableWeights = new Map();
const characterWeights = new Map();
for (const { text, code, weight } of rows('8105.dict.yaml')) {
  if (!isSyllable(code)) continue;
  syllableWeights.set(code, (syllableWeights.get(code) ?? 0) + weight);
  characterWeights.set(text, (characterWeights.get(text) ?? 0) + weight);
}

const wordWeights = new Map();
for (const { code, weight } of rows('base.dict.yaml')) {
  const syllables = code.split(' ');
  if (syllables.length < 2 || !syllables.every(s => syllableWeights.has(s))) continue;
  const key = syllables.join('');
  if ((wordWeights.get(key) ?? -1) < weight) wordWeights.set(key, weight);
}

// Every character CP932 (Windows Japanese) can encode
const cp932 = new Set();
const decoder = new TextDecoder('shift_jis');
for (let lead = 0x81; lead <= 0xfc; lead++) {
  if (lead > 0x9f && lead < 0xe0) continue;
  for (let trail = 0x40; trail <= 0xfc; trail++) {
    if (trail === 0x7f) continue;
    const c = decoder.decode(new Uint8Array([lead, trail]));
    if (c.length === 1 && c !== '\ufffd') cp932.add(c);
  }
}
if (!cp932.has('漢') || cp932.has('们')) throw new Error('this Node.js cannot decode Shift_JIS (needs full ICU)');

const byWeight = map => [...map].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).map(([key]) => key);
const tier = (map, min, max = Infinity) => new Map([...map].filter(([, w]) => w >= min && w < max));

function lines(name, items, separator = ' ', width = 100) {
  const out = [];
  let line = name;
  for (const item of items) {
    if (line.length + separator.length + item.length > width && line !== name) {
      out.push(line);
      line = name;
    }
    line += (line === name ? ' ' : separator) + item;
  }
  if (line !== name) out.push(line);
  return out;
}

const simplified = [...characterWeights]
  .filter(([c, w]) => w >= SimplifiedWeight && [...c].length === 1 && !cp932.has(c))
  .sort((a, b) => b[1] - a[1])
  .map(([c]) => c);

const out = [
  '# Meltype pinyin syllables and words used to weigh Chinese (pinyin) candidates in the composition lattice.',
  `# Generated by tools/make-chinese-pinyin.mjs from rime-ice (https://github.com/iDvel/rime-ice) at ${RimeIceCommit}.`,
  '# rime-ice is published under the GNU General Public License v3.0.',
  '# Each data line is "<tier> <items>"; syllable and word lines list pinyin without tones (ü is v), most frequent first.',
  `# syllable-common / syllable-standard / syllable-rare: summed weight of the characters in cn_dicts/8105.dict.yaml (>= ${CommonSyllableWeight} / >= ${StandardSyllableWeight} / less).`,
  `# word-common / word-standard: words of two or more syllables in cn_dicts/base.dict.yaml, by their highest weight (>= ${CommonWordWeight} / >= ${StandardWordWeight}).`,
  `# simplified: characters in cn_dicts/8105.dict.yaml with weight >= ${SimplifiedWeight} that CP932 cannot encode, so Japanese text does not use them.`,
  ...lines('syllable-common', byWeight(tier(syllableWeights, CommonSyllableWeight))),
  ...lines('syllable-standard', byWeight(tier(syllableWeights, StandardSyllableWeight, CommonSyllableWeight))),
  ...lines('syllable-rare', byWeight(tier(syllableWeights, 0, StandardSyllableWeight))),
  ...lines('word-common', byWeight(tier(wordWeights, CommonWordWeight))),
  ...lines('word-standard', byWeight(tier(wordWeights, StandardWordWeight, CommonWordWeight))),
  ...lines('simplified', simplified, ''),
];
process.stdout.write(out.join('\n') + '\n');
